pub(crate) fn emit_scripted_effect_card_hoi4yaml(out: &mut String, card: &Card, effect_id: &str) {
    let scope = scripted_helper_scope(card);
    let effect_text =
        join_existing_fields(&card.fields, &["效果", "动作", "内容", "执行"]).unwrap_or_default();
    let suggestions = suggest_common("scripted_effect", &effect_text, None, None, None, None);
    let (effect_lines, effect_comments) = scripted_effect_lines(&suggestions, scope);
    out.push_str(&format!("    {}:\n", yaml_key(effect_id)));
    out.push_str(&format!("      _scope: {}\n", yaml_string(scope)));
    if effect_lines.is_empty() && effect_comments.is_empty() {
        if effect_text.trim().is_empty() {
            out.push_str("      # TODO: add scripted effect body\n");
        } else {
            emit_yaml_comment(out, "      ", &effect_text);
        }
    }
    emit_hoi4_assignment_lines_as_yaml(out, "      ", &effect_lines);
    for comment in effect_comments {
        emit_yaml_comment(out, "      ", &comment);
    }
}

pub(crate) fn emit_state_effect_card_hoi4yaml(
    out: &mut String,
    card: &Card,
    effect_id: &str,
    target: &str,
) {
    let state_target = state_card_target(card);
    let suggestions = state_card_suggestions(card, target);
    let (effect_lines, effect_comments) = state_effect_body_lines(&suggestions);
    out.push_str(&format!("    {}:\n", yaml_key(effect_id)));
    if let Some(state_id) = state_target.id {
        out.push_str(&format!("      _state_id: {state_id}\n"));
    } else {
        out.push_str("      _scope: \"state\"\n");
    }
    if let Some(label) = state_target.label.as_deref() {
        out.push_str(&format!("      _state: {}\n", yaml_string(label)));
    }
    if effect_lines.is_empty() && effect_comments.is_empty() {
        out.push_str("      # TODO: add state effects from card text\n");
    }
    emit_hoi4_assignment_lines_as_yaml(out, "      ", &effect_lines);
    for comment in effect_comments {
        emit_yaml_comment(out, "      ", &comment);
    }
}

pub(crate) fn emit_scripted_trigger_card_hoi4yaml(out: &mut String, card: &Card, trigger_id: &str) {
    let trigger_text = join_existing_fields(
        &card.fields,
        &["条件", "触发", "可用", "可见", "限制", "内容"],
    )
    .unwrap_or_default();
    let suggestions = split_cn_list(&trigger_text)
        .into_iter()
        .flat_map(suggest_trigger)
        .collect::<Vec<_>>();
    let (trigger_lines, trigger_comments) = trigger_lines_and_comments(&suggestions);
    out.push_str(&format!("    {}:\n", yaml_key(trigger_id)));
    if trigger_lines.is_empty() && trigger_comments.is_empty() {
        if trigger_text.trim().is_empty() {
            out.push_str("      # TODO: add scripted trigger body\n");
        } else {
            emit_yaml_comment(out, "      ", &trigger_text);
        }
    }
    emit_hoi4_assignment_lines_as_yaml(out, "      ", &trigger_lines);
    for comment in trigger_comments {
        emit_yaml_comment(out, "      ", &comment);
    }
}

pub(crate) fn emit_event_cards_hoi4yaml(out: &mut String, text: &str, tag: &str, prefix: &str) {
    let cards = parse_cards(text, &["事件"]);
    let event_ids = event_card_numbered_ids(&cards, prefix);
    let mut loc_entries = BTreeMap::new();
    for (card, (_, event_id)) in cards.iter().zip(event_ids.iter()) {
        insert_event_localisation(card, event_id, &mut loc_entries);
    }

    out.push_str("events:\n");
    out.push_str(&format!(
        "  - _file: {}\n",
        yaml_string(&format!("{prefix}_events"))
    ));
    let namespaces = event_ids
        .iter()
        .map(|(namespace, _)| namespace.to_string())
        .collect::<BTreeSet<_>>();
    if namespaces.len() == 1 {
        if let Some(namespace) = namespaces.iter().next() {
            out.push_str(&format!("    _namespace: {}\n", yaml_string(namespace)));
        }
    } else if !namespaces.is_empty() {
        out.push_str("    _namespaces:\n");
        for namespace in namespaces {
            out.push_str(&format!("      - {}\n", yaml_string(&namespace)));
        }
    }
    let mut grouped: BTreeMap<String, Vec<(usize, &Card)>> = BTreeMap::new();
    for (idx, (card, _)) in cards.iter().zip(event_ids.iter()).enumerate() {
        let event_type = normalize_event_type(card.fields.get("类型").map(String::as_str));
        grouped
            .entry(event_type.to_string())
            .or_default()
            .push((idx, card));
    }
    for (event_type, items) in grouped {
        out.push_str(&format!("    {}:\n", yaml_key(&event_type)));
        for (idx, card) in items {
            let (_, event_id) = &event_ids[idx];
            emit_event_card_hoi4yaml(out, card, event_id, tag);
        }
    }
    out.push('\n');
    emit_localisation_yaml(out, &loc_entries);
}

pub(crate) fn emit_event_card_hoi4yaml(out: &mut String, card: &Card, event_id: &str, tag: &str) {
    let picture = card
        .fields
        .get("图片")
        .map(String::as_str)
        .unwrap_or("GFX_report_event_generic");
    let trigger = card.fields.get("触发").or_else(|| card.fields.get("条件"));
    let trigger_lines = trigger
        .map(|text| {
            split_cn_list(text)
                .into_iter()
                .flat_map(suggest_trigger)
                .filter(|suggestion| suggestion.kind == "trigger")
                .filter_map(|suggestion| concrete_suggestion_code(&suggestion))
                .collect::<Vec<_>>()
        })
        .unwrap_or_else(|| vec![format!("tag = {tag}")]);

    out.push_str(&format!("      - id: {}\n", yaml_string(event_id)));
    out.push_str(&format!(
        "        title: {}\n",
        yaml_string(&format!("{event_id}.t"))
    ));
    out.push_str(&format!(
        "        desc: {}\n",
        yaml_string(&format!("{event_id}.d"))
    ));
    out.push_str(&format!("        picture: {}\n", yaml_string(picture)));
    out.push_str("        is_triggered_only: true\n");
    if !trigger_lines.is_empty() {
        out.push_str("        trigger:\n");
        emit_hoi4_assignment_lines_as_yaml(out, "          ", &trigger_lines);
    }
    out.push_str("        option:\n");
    for option in event_options(card) {
        out.push_str(&format!(
            "          - name: {}\n",
            yaml_string(&format!("{event_id}.{}", option.key))
        ));
        if let Some(factor) = parse_int(&option.ai_chance) {
            out.push_str("            ai_chance:\n");
            out.push_str(&format!("              factor: {factor}\n"));
        }
        let suggestions = suggest_common("event", &option.effects, None, None, None, None);
        let (effect_lines, effect_comments) = decision_effect_lines(&suggestions);
        if option.effects.trim().is_empty() && option.hidden_effects.trim().is_empty() {
            out.push_str("            # TODO: add option effects\n");
        }
        emit_hoi4_assignment_lines_as_yaml(out, "            ", &effect_lines);
        for comment in effect_comments {
            emit_yaml_comment(out, "            ", &comment);
        }
        if !option.hidden_effects.trim().is_empty() {
            let hidden_suggestions =
                suggest_common("event", &option.hidden_effects, None, None, None, None);
            let (hidden_lines, hidden_comments) = decision_effect_lines(&hidden_suggestions);
            out.push_str("            hidden_effect:\n");
            if hidden_lines.is_empty() && hidden_comments.is_empty() {
                emit_yaml_comment(out, "              ", &option.hidden_effects);
            }
            emit_hoi4_assignment_lines_as_yaml(out, "              ", &hidden_lines);
            for comment in hidden_comments {
                emit_yaml_comment(out, "              ", &comment);
            }
        }
    }
}

pub(crate) fn emit_yaml_string_or_list(
    out: &mut String,
    indent: &str,
    key: &str,
    values: &[String],
) {
    if values.is_empty() {
        return;
    }
    if values.len() == 1 {
        out.push_str(&format!("{indent}{key}: {}\n", yaml_string(&values[0])));
    } else {
        out.push_str(&format!("{indent}{key}:\n"));
        for value in values {
            out.push_str(&format!("{indent}  - {}\n", yaml_string(value)));
        }
    }
}

pub(crate) fn emit_hoi4_assignment_lines_as_yaml(out: &mut String, indent: &str, lines: &[String]) {
    for line in lines {
        emit_hoi4_assignment_as_yaml(out, indent, line);
    }
}

pub(crate) fn emit_hoi4_assignment_as_yaml(out: &mut String, indent: &str, line: &str) {
    let line = line.trim();
    if line.is_empty() {
        return;
    }
    if line.contains('{') || line.contains('}') || line.contains('\n') {
        emit_yaml_comment(
            out,
            indent,
            &format!("TODO raw HOI4 block: {}", flatten_ws(line)),
        );
        return;
    }
    let Some((key, value)) = line.split_once('=') else {
        emit_yaml_comment(
            out,
            indent,
            &format!("TODO unmapped line: {}", flatten_ws(line)),
        );
        return;
    };
    out.push_str(&format!(
        "{}{}: {}\n",
        indent,
        yaml_key(key.trim()),
        yaml_hoi4_value(value.trim())
    ));
}

pub(crate) fn emit_localisation_yaml(out: &mut String, entries: &BTreeMap<String, String>) {
    if entries.is_empty() {
        return;
    }
    out.push_str("localisation:\n");
    out.push_str("  simp_chinese:\n");
    for (key, value) in entries {
        out.push_str(&format!("    {}: {}\n", yaml_key(key), yaml_string(value)));
    }
}

pub(crate) fn emit_yaml_comment(out: &mut String, indent: &str, comment: &str) {
    for line in flatten_ws(comment).lines() {
        out.push_str(&format!("{indent}# {line}\n"));
    }
}

pub(crate) fn flatten_ws(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

pub(crate) fn yaml_key(key: &str) -> String {
    if !key.is_empty()
        && !key.starts_with('-')
        && key
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '_' | '-' | '.'))
    {
        key.to_string()
    } else {
        yaml_string(key)
    }
}

pub(crate) fn yaml_string(value: &str) -> String {
    json_str(value)
}

pub(crate) fn yaml_hoi4_value(value: &str) -> String {
    if value == "yes" {
        "true".to_string()
    } else if value == "no" {
        "false".to_string()
    } else if value.parse::<i64>().is_ok() || value.parse::<f64>().is_ok() {
        value.to_string()
    } else {
        yaml_string(value)
    }
}
