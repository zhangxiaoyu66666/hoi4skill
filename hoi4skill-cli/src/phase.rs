//! Phase-level capability reports for the large-mod authoring core.
//!
//! This is the P0 entry point: it does not generate HOI4 code. It gives the
//! user and future agents a single machine-readable baseline for what exists,
//! what is planned, and which phase is allowed to run full validation.

#[allow(unused_imports)]
use crate::*;

#[derive(Clone, Copy)]
struct PhaseRow {
    id: &'static str,
    title: &'static str,
    status: &'static str,
    ready: bool,
    acceptance: &'static str,
}

#[derive(Clone, Copy)]
struct CapabilityRow {
    phase: &'static str,
    id: &'static str,
    command: &'static str,
    status: &'static str,
    lane: &'static str,
    evidence: &'static str,
    note: &'static str,
}

pub(crate) fn cmd_core_capability_audit(args: &[String]) -> Result<(), String> {
    let map = parse_args(args);
    let phase_filter = value(&map, "phase")
        .or_else(|| value(&map, "p"))
        .map(|value| value.to_ascii_uppercase());
    let selected_phases = selected_phase_rows(phase_filter.as_deref())?;
    let selected_capabilities = selected_capability_rows(phase_filter.as_deref());
    let all_selected_ready = selected_phases.iter().all(|phase| phase.ready);
    let json = render_core_capability_audit_json(
        phase_filter.as_deref(),
        &selected_phases,
        &selected_capabilities,
        all_selected_ready,
    );
    write_or_print(&json, value(&map, "output"))?;

    if let Some(output) = value(&map, "markdown-output") {
        let markdown = render_core_capability_audit_markdown(
            phase_filter.as_deref(),
            &selected_phases,
            &selected_capabilities,
            all_selected_ready,
        );
        write_or_print(&markdown, Some(output))?;
    }

    if map.flags.contains("require-passed") && !all_selected_ready {
        return Err(format!(
            "selected phase set is not ready; rerun with a narrower completed phase such as --phase P0 or finish blockers first"
        ));
    }

    Ok(())
}

fn selected_phase_rows(filter: Option<&str>) -> Result<Vec<PhaseRow>, String> {
    let phases = core_phase_rows();
    if let Some(filter) = filter {
        if filter != "ALL" && !phases.iter().any(|phase| phase.id == filter) {
            return Err(format!(
                "unknown --phase {filter}; expected P0, P1, P2, P3, P4, P5, P6, P7, P8, P9, P10, P11, P12, P13, P14, P15, P16, P17, P18, P19, P20, P21, P22, P23, P24, P25, P26, P27, P28, P29, P30, P31, P32, P33, P34, P35, P36, P37, P38, P39, P40, P41, P42, P43, P44, P45, P46, P47, P48, P49, P50, P51, P52, P53, P61, P62, P63, P64, P65, P66, P71, P72, P73, P74, P75, P76, P77, P78, P79, P80, P81, P82, P91, P92, P93, P94, P98, P101, P102, P103, P104, P105, P106, P107, P108, P109, P110, P111, P112, P113, P114, P115, P116, or all"
            ));
        }
    }
    Ok(phases
        .into_iter()
        .filter(|phase| phase_selected(phase.id, filter))
        .collect())
}

fn selected_capability_rows(filter: Option<&str>) -> Vec<CapabilityRow> {
    core_capability_rows()
        .into_iter()
        .filter(|capability| phase_selected(capability.phase, filter))
        .collect()
}

fn phase_selected(phase: &str, filter: Option<&str>) -> bool {
    match filter {
        Some("ALL") | None => true,
        Some(filter) => phase == filter,
    }
}

