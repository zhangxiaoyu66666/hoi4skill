fn render_core_capability_audit_json(
    filter: Option<&str>,
    phases: &[PhaseRow],
    capabilities: &[CapabilityRow],
    all_selected_ready: bool,
) -> String {
    let implemented_count = capabilities
        .iter()
        .filter(|capability| capability.status == "implemented")
        .count();
    let planned_count = capabilities
        .iter()
        .filter(|capability| capability.status.starts_with("planned"))
        .count();
    let ready_count = phases.iter().filter(|phase| phase.ready).count();
    let mut map = BTreeMap::new();
    map.insert(
        "schema".to_string(),
        json_str("hoi4skill.core_capability_audit.v1"),
    );
    map.insert("ok".to_string(), json_bool(all_selected_ready).to_string());
    map.insert(
        "status".to_string(),
        json_str(if all_selected_ready {
            "phase_ready"
        } else {
            "planned_gaps_present"
        }),
    );
    map.insert("phase_filter".to_string(), json_optional_str(filter));
    map.insert("phase_count".to_string(), phases.len().to_string());
    map.insert("phase_ready_count".to_string(), ready_count.to_string());
    map.insert(
        "capability_count".to_string(),
        capabilities.len().to_string(),
    );
    map.insert(
        "implemented_count".to_string(),
        implemented_count.to_string(),
    );
    map.insert("planned_count".to_string(), planned_count.to_string());
    map.insert("phases".to_string(), render_phase_array(phases));
    map.insert(
        "capabilities".to_string(),
        render_capability_array(capabilities),
    );
    map.insert(
        "test_policy".to_string(),
        json_array(&[
            "fast local checks may run while editing a phase".to_string(),
            "full validation runs only when a P stage is complete".to_string(),
            "phase_report.json and phase_report.md must record completed, skipped, failed, risk, and ready_for_next_phase".to_string(),
        ]),
    );
    map.insert(
        "ai_code_rules".to_string(),
        json_array(&[
            "AI may plan, classify, choose templates, and explain choices".to_string(),
            "AI must not invent Clausewitz symbols or engine syntax".to_string(),
            "Rust CLI indexes, recommends, assembles, writes, and validates".to_string(),
            "unknown trigger, effect, modifier, sprite, tag, technology, or scope symbol is a hard error".to_string(),
        ]),
    );
    map.insert(
        "next_commands".to_string(),
        json_array(&[
            "hoi4skill core-capability-audit --phase all --require-passed --output .hoi4skill/phase_report.json --markdown-output .hoi4skill/phase_report.md".to_string(),
            "run phase-specific command targets from NON_VISUAL_LARGE_MOD_P_PLAN.md against the real target mod before release".to_string(),
        ]),
    );
    json_raw_object(&map)
}

fn render_phase_array(phases: &[PhaseRow]) -> String {
    format!(
        "[{}]",
        phases
            .iter()
            .map(|phase| {
                let mut map = BTreeMap::new();
                map.insert("id".to_string(), json_str(phase.id));
                map.insert("title".to_string(), json_str(phase.title));
                map.insert("status".to_string(), json_str(phase.status));
                map.insert("ready".to_string(), json_bool(phase.ready).to_string());
                map.insert("acceptance".to_string(), json_str(phase.acceptance));
                json_raw_object(&map)
            })
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn render_capability_array(capabilities: &[CapabilityRow]) -> String {
    format!(
        "[{}]",
        capabilities
            .iter()
            .map(|capability| {
                let mut map = BTreeMap::new();
                map.insert("phase".to_string(), json_str(capability.phase));
                map.insert("id".to_string(), json_str(capability.id));
                map.insert("command".to_string(), json_str(capability.command));
                map.insert("status".to_string(), json_str(capability.status));
                map.insert("lane".to_string(), json_str(capability.lane));
                map.insert("evidence".to_string(), json_str(capability.evidence));
                map.insert("note".to_string(), json_str(capability.note));
                json_raw_object(&map)
            })
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn render_core_capability_audit_markdown(
    filter: Option<&str>,
    phases: &[PhaseRow],
    capabilities: &[CapabilityRow],
    all_selected_ready: bool,
) -> String {
    let mut out = String::new();
    out.push_str("# HOI4Skill Core Capability Phase Report\n\n");
    out.push_str(&format!("- phase_filter: `{}`\n", filter.unwrap_or("all")));
    out.push_str(&format!(
        "- status: `{}`\n",
        if all_selected_ready {
            "phase_ready"
        } else {
            "planned_gaps_present"
        }
    ));
    out.push_str(&format!(
        "- ready_for_next_phase: `{}`\n\n",
        if all_selected_ready { "yes" } else { "no" }
    ));
    out.push_str("## Phases\n\n");
    for phase in phases {
        out.push_str(&format!(
            "- `{}` `{}` ready=`{}`: {}\n",
            phase.id, phase.status, phase.ready, phase.acceptance
        ));
    }
    out.push_str("\n## Capabilities\n\n");
    for capability in capabilities {
        out.push_str(&format!(
            "- `{}` `{}` `{}`: {} ({})\n",
            capability.phase,
            capability.status,
            capability.command,
            capability.note,
            capability.evidence
        ));
    }
    out.push_str("\n## Test Policy\n\n");
    out.push_str("- Fast local checks may run while editing a phase.\n");
    out.push_str("- Full validation runs only when a P stage is complete.\n");
    out.push_str("- Every phase report must record completed, skipped, failed, risk, and ready_for_next_phase.\n");
    out
}
